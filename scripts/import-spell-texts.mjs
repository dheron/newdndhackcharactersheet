// Builds src/rules/data/spell-texts.json from sources/spell-compendium.md, the Spell Compendium
// (1uvEi5cgM7sd6U6fmZQaH0iNzc_T5SdbKK1LJdmwFX0I) exported from Google Docs as Markdown.
// Re-export the doc into that file after it changes, then run: npm run rules
import { readFileSync, writeFileSync } from "node:fs";

const md = readFileSync(new URL("../sources/spell-compendium.md", import.meta.url), "utf8");
const unescape = (s) => s.replace(/\\([|[\]+*_#.\-()!])/g, "$1").trim();

const spells = {};
const lines = md.split("\n");
for (let i = 0; i < lines.length; i++) {
  const m = /^### \*\*(.+?)\*\* \\\| (.+)$/.exec(lines[i]);
  if (!m) continue;
  const name = unescape(m[1]);
  // "3rd • Evocation \[1 hr\] \[Wi 3, Dr 3\]": level, school, optional duration, then the class tags.
  const rest = unescape(m[2]);
  const tags = [...rest.matchAll(/\[([^\]]+)\]/g)].map((t) => t[1]);
  const head = rest.replace(/\s*\[[^\]]+\]/g, "").trim();
  const [level, school] = head.split("•").map((s) => s.trim());
  const classes = tags.length ? tags[tags.length - 1] : "";
  const duration = tags.length > 1 ? tags[0] : null;
  const body = [];
  for (let j = i + 1; j < lines.length && !/^#{1,3} /.test(lines[j]); j++) if (lines[j].trim()) body.push(unescape(lines[j]));
  spells[name] = { level, school, duration, classes, text: body.join("\n") };
}

const out = {
  source: "Spell Compendium (1uvEi5cgM7sd6U6fmZQaH0iNzc_T5SdbKK1LJdmwFX0I)",
  note: "Generated by scripts/import-spell-texts.mjs from sources/spell-compendium.md. Text keeps the doc's **bold** and *italic* marks.",
  spells,
};
writeFileSync(new URL("../src/rules/data/spell-texts.json", import.meta.url), JSON.stringify(out, null, 2) + "\n");
console.log(`Wrote src/rules/data/spell-texts.json (${Object.keys(spells).length} spells)`);
