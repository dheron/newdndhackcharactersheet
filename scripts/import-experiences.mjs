// Builds src/rules/data/expanded-experiences.json from sources/expanded-experiences.md, the
// "Expanded Experiences" doc (12JgZ4ylpu_9M7fsrITbyPUEhrZg8bB5oI0lHoK48D_Q) exported from Google
// Docs as Markdown. Re-export the doc into that file after it changes, then run: npm run rules
// Section 4 phrases keep only the phrase: the words in brackets are dropped (David).
import { readFileSync, writeFileSync } from "node:fs";

const md = readFileSync(new URL("../sources/expanded-experiences.md", import.meta.url), "utf8");
const unescape = (s) => s.replace(/\\([-*_()[\]!.+#'])/g, "$1").trim();

const out = { coreSkills: [], defaultExamples: [], sections: [] };
let list = null;
let section = null;
for (const raw of md.split("\n")) {
  const line = raw.trim();
  let m;
  if ((m = /^##\s+(?:\*\*)?DnD Core Skills/i.exec(line))) list = out.coreSkills;
  else if (/^(?:#+\s*)?(?:\*\*)?Default Examples/i.test(line)) list = out.defaultExamples;
  else if ((m = /^##\s+(?:\*\*)?Section (\d+):\s*(.+?)(?:\*\*)?$/.exec(line))) {
    section = { number: Number(m[1]), title: unescape(m[2]), groups: [] };
    out.sections.push(section);
    list = null;
  } else if ((m = /^###\s+(?:\*\*)?(.+?)(?:\*\*)?$/.exec(line)) && section) {
    const group = { title: unescape(m[1]), items: [] };
    section.groups.push(group);
    list = group.items;
  } else if (/^#/.test(line)) list = null;
  else if ((m = /^[*-]\s+(.+)$/.exec(line)) && list) {
    let item = unescape(m[1]);
    if (section?.number === 4) item = item.replace(/\s*\(.*\)\s*$/, "");
    if (item) list.push(item);
  }
}

const result = {
  source: "Expanded Experiences (12JgZ4ylpu_9M7fsrITbyPUEhrZg8bB5oI0lHoK48D_Q)",
  note: "Generated by scripts/import-experiences.mjs from sources/expanded-experiences.md. Section 4 phrases have the bracketed notes removed (David).",
  ...out,
};
writeFileSync(new URL("../src/rules/data/expanded-experiences.json", import.meta.url), JSON.stringify(result, null, 2) + "\n");
const count = out.sections.reduce((t, s) => t + s.groups.reduce((u, g) => u + g.items.length, 0), 0);
console.log(`Wrote src/rules/data/expanded-experiences.json (${out.coreSkills.length} core skills, ${out.defaultExamples.length} default examples, ${out.sections.length} sections, ${count} entries)`);
