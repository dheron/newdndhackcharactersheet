const sign = (n) => (n > 0 ? `+${n}` : `${n}`);
const cell = (v) => (v === null || v === undefined || v === "" ? "**(blank)**" : String(v).replace(/\|/g, "\\|"));
const table = (head, rows) => {
  out(`| ${head.join(" | ")} |`);
  out(`|${head.map(() => "---").join("|")}|`);
  for (const r of rows) out(`| ${r.map(cell).join(" | ")} |`);
  out();
};

